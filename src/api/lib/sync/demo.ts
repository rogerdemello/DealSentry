/**
 * Demo-mode sync: connections made through the *_DEMO_MODE OAuth flows store
 * `credentials.demo = true` and import canned deals, so connect → sync → review
 * is fully demonstrable without real CRM credentials.
 */

import { baseProposal, importedIds, insertProposals, failureResult, successResult, type SyncContext, type SyncResult } from './common';

export const sampleDeals = (sourceKey: string) => [
  { id: `demo-${sourceKey}-001`, name: 'Acme Corp — Platform Renewal', amount: 120000, stage: 'Negotiation', client: 'Acme Corp' },
  { id: `demo-${sourceKey}-002`, name: 'Globex — Data Migration', amount: 45000, stage: 'Proposal Sent', client: 'Globex Inc' },
  { id: `demo-${sourceKey}-003`, name: 'Initech — Annual Support Contract', amount: 24000, stage: 'Qualification', client: 'Initech LLC' },
];

export async function syncDemo(ctx: SyncContext): Promise<SyncResult> {
  const { integration } = ctx;
  const sourceKey = String(integration.type || 'crm').toLowerCase();

  try {
    const existing = await importedIds(ctx.userId, 'dealId');
    const newDeals = sampleDeals(sourceKey).filter((d) => !existing.has(d.id));

    if (newDeals.length === 0) {
      return successResult(0, {
        message: 'Demo sync complete — all sample deals already imported.',
        demo: true,
        proposalsCreated: 0,
      });
    }

    const created = await insertProposals(
      newDeals.map((deal) => ({
        id: crypto.randomUUID(),
        title: deal.name,
        content: `Deal imported from ${integration.name} (demo mode)\n\nClient: ${deal.client}\nAmount: $${deal.amount.toLocaleString()}\nStage: ${deal.stage}\n\nThis record was generated by the demo integration to showcase the CRM import flow.`,
        ...baseProposal(ctx),
        metadata: {
          clientName: deal.client,
          dealSize: deal.amount,
          source: `${sourceKey}-demo`,
          dealId: deal.id,
          stageName: deal.stage,
          importedAt: new Date().toISOString(),
        },
      }))
    );

    return successResult(created, {
      message: `Demo sync imported ${created} sample deals from ${integration.name}`,
      demo: true,
      proposalsCreated: created,
    });
  } catch (err) {
    return failureResult(err, 'Demo sync failed');
  }
}
